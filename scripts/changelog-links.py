"""Turn issue, pull request and user references in CHANGELOG.md into links.

GitHub links `#123` and `@user` in issues, pull requests and release notes,
but not in a rendered Markdown file. This rewrites them:

- `#123` becomes the reference link `[#123]`, defined at the end of the file
  as https://github.com/frankea/Whisky/issues/123 (GitHub redirects a pull
  request number there to the pull request).
- `@user` becomes `[@user]`, defined as https://github.com/user.
- `owner/repo#123` and `upstream #123` (the archived whisky-app/whisky) become
  inline links, since their numbers would collide with this repository's.
- The version headings get release links (`app-vX.Y.Z` tags), and
  `[Unreleased]` compares the newest app release with HEAD. A heading marked
  `(App)` links to its `app-v` tag even before the tag is pushed, so the
  release commit already carries the right links.

Text inside backticks is left alone, and so are references listed in
UNLINKED (issues that no longer exist). Running it again changes nothing.

Usage: scripts/changelog-links.py [--check]
"""

import re
import subprocess
import sys
from pathlib import Path

REPO = "https://github.com/frankea/Whisky"
UPSTREAM = "https://github.com/whisky-app/whisky"
CHANGELOG = Path(__file__).resolve().parent.parent / "CHANGELOG.md"
MARKER = "<!-- Links below are generated by scripts/changelog-links.py. -->"

# Issue numbers that are cited but no longer exist on GitHub.
UNLINKED = {198}
# Words written with @ that are not GitHub users.
NOT_USERS = {"unchecked", "MainActor", "available", "objc", "Published", "State"}

CROSS_REPO_RE = re.compile(r"(?<![\w\[/.-])([A-Za-z0-9-]+/[A-Za-z0-9._-]+)#(\d+)\b")
UPSTREAM_RUN_RE = re.compile(r"\bupstream (#\d+(?:, #\d+)*)")
ISSUE_RE = re.compile(r"(?<![\w/\[&])#(\d+)\b(?!\]|\()")
USER_RE = re.compile(r"(?<![\w\[`])@([A-Za-z0-9](?:[A-Za-z0-9-]*[A-Za-z0-9])?)\b(?!\])")
HEADING_RE = re.compile(r"^## \[([^\]]+)\]")


LINK_RE = re.compile(r"(\[[^\]]*\](?:\([^)]*\))?)")


def outside_links(text: str, transform) -> str:
    """Applies transform to the parts of text that are not already links."""
    parts = LINK_RE.split(text)
    for index in range(0, len(parts), 2):
        parts[index] = transform(parts[index])
    return "".join(parts)


def link_prose(text: str, issues: set, users: set) -> str:
    """Rewrites references in text that is outside code spans."""

    def cross_repo(match):
        repo, number = match.group(1), match.group(2)
        return f"[{repo}#{number}](https://github.com/{repo}/issues/{number})"

    text = outside_links(text, lambda part: CROSS_REPO_RE.sub(cross_repo, part))

    def upstream_run(match):
        refs = re.sub(
            r"#(\d+)", lambda m: f"[#{m.group(1)}]({UPSTREAM}/issues/{m.group(1)})", match.group(1)
        )
        return f"upstream {refs}"

    text = outside_links(text, lambda part: UPSTREAM_RUN_RE.sub(upstream_run, part))

    def issue(match):
        number = int(match.group(1))
        if number in UNLINKED:
            return match.group(0)
        issues.add(number)
        return f"[#{number}]"

    def user(match):
        name = match.group(1)
        if name in NOT_USERS:
            return match.group(0)
        users.add(name)
        return f"[@{name}]"

    text = outside_links(text, lambda part: ISSUE_RE.sub(issue, part))
    text = outside_links(text, lambda part: USER_RE.sub(user, part))
    # Existing reference links still count, so a rerun keeps their definitions.
    issues.update(int(n) for n in re.findall(r"\[#(\d+)\](?!\()", text))
    users.update(re.findall(r"\[@([A-Za-z0-9-]+)\](?!\()", text))
    return text


def app_tags() -> list:
    """App release tags, oldest first."""
    output = subprocess.run(
        ["git", "tag", "-l", "app-v*"], capture_output=True, text=True, check=True, cwd=CHANGELOG.parent
    ).stdout.split()

    def key(tag):
        return [int(part) for part in tag.removeprefix("app-v").split(".")]

    return sorted(output, key=key)


def build(text: str) -> str:
    body = text.split(MARKER)[0].rstrip("\n")
    # Drop hand-written version link definitions; they are regenerated.
    body = re.sub(r"(?m)^\[(Unreleased|\d+\.\d+\.\d+)\]: \S+\n?", "", body).rstrip("\n")

    issues, users, versions, app_versions = set(), set(), [], set()
    out_lines = []
    for line in body.split("\n"):
        heading = HEADING_RE.match(line)
        if heading:
            versions.append(heading.group(1))
            if "(App)" in line:
                app_versions.add(heading.group(1))
            out_lines.append(line)
            continue
        if line.startswith("[") and "]: http" in line:
            out_lines.append(line)
            continue
        segments = line.split("`")
        for index in range(0, len(segments), 2):
            segments[index] = link_prose(segments[index], issues, users)
        out_lines.append("`".join(segments))

    tags = app_tags()
    definitions = []
    # Headings run newest first, so the first app heading is the newest release.
    newest_app = next((f"app-v{v}" for v in versions if v in app_versions), tags[-1] if tags else None)
    if "Unreleased" in versions and newest_app:
        definitions.append(f"[Unreleased]: {REPO}/compare/{newest_app}...HEAD")
    seen = set()
    for version in versions:
        if version == "Unreleased" or version in seen:
            continue
        seen.add(version)
        is_app = version in app_versions or f"app-v{version}" in tags
        tag = f"app-v{version}" if is_app else f"v{version}"
        definitions.append(f"[{version}]: {REPO}/releases/tag/{tag}")
    definitions += [f"[#{number}]: {REPO}/issues/{number}" for number in sorted(issues)]
    definitions += [f"[@{name}]: https://github.com/{name}" for name in sorted(users, key=str.lower)]

    return "\n".join(out_lines) + "\n\n" + MARKER + "\n\n" + "\n".join(definitions) + "\n"


def main() -> int:
    current = CHANGELOG.read_text()
    updated = build(current)
    if "--check" in sys.argv[1:]:
        if updated != current:
            print("CHANGELOG.md has unlinked references; run scripts/changelog-links.py")
            return 1
        return 0
    if updated != current:
        CHANGELOG.write_text(updated)
        print("CHANGELOG.md updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
